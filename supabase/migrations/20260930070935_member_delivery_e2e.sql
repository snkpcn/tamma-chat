  add constraint otop_orders_shipping_status_check check (
    shipping_status is null or shipping_status in (
      'awaiting_payment','packing','ready_to_ship','shipped',
      'delivered','delivery_failed','returned','cancelled'
    )
  );

create unique index if not exists otop_orders_checkout_idempotency_uq
  on public.otop_orders(customer_id, checkout_idempotency_key)
  where checkout_idempotency_key is not null;
create index if not exists otop_orders_shipping_queue_idx
  on public.otop_orders(environment, shipping_status, created_at desc)
  where fulfillment_type = 'shipping';

create table if not exists public.otop_shipping_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.otop_orders(id) on delete cascade,
  status text not null check (status in (
    'awaiting_payment','packing','ready_to_ship','shipped',
    'delivered','delivery_failed','returned','cancelled'
  )),
  customer_message text null check (customer_message is null or char_length(customer_message) <= 500),
  actor text null check (actor is null or char_length(actor) <= 120),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists otop_shipping_events_order_idx
  on public.otop_shipping_events(order_id, created_at asc);
