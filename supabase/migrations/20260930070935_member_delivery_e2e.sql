create or replace view public.ops_order_queue with (security_invoker=true) as
select o.id,o.order_code,o.status,o.fulfillment_type,o.total_amount,o.contact_status,
  o.source_channel,o.environment,o.customer_id,c.full_name_enc,c.email_enc,c.phone_enc,
  c.preferred_contact,c.is_test,c.test_label,o.customer_note,o.staff_note,o.created_at,o.updated_at,
  o.shipping_address_id,o.shipping_recipient_name_enc,o.shipping_phone_enc,o.shipping_address_enc,
  o.subtotal_amount,o.shipping_fee,o.shipping_status,o.carrier_name,o.tracking_number_enc,
  o.tracking_url,o.shipped_at,o.delivered_at
from public.otop_orders o
left join public.customer_accounts c on c.id=o.customer_id;

