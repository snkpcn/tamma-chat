-- Member delivery v1: encrypted reusable addresses, atomic multi-item OTOP
-- checkout, shipping totals, tracking and customer-visible status history.

create table if not exists public.customer_addresses (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customer_accounts(id) on delete cascade,
  label text not null check (char_length(label) between 1 and 60),
  recipient_name_enc text not null,
  phone_enc text not null,
  address_line1_enc text not null,
  address_line2_enc text null,
  subdistrict_enc text null,
  district_enc text not null,
  province text not null check (char_length(province) between 1 and 80),
  postal_code_enc text not null,
  delivery_instructions_enc text null,
  is_default boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists customer_addresses_customer_idx
  on public.customer_addresses(customer_id, active, created_at desc);
create unique index if not exists customer_addresses_one_default_uq
  on public.customer_addresses(customer_id) where is_default and active;

alter table public.customer_addresses enable row level security;
revoke all on table public.customer_addresses from public, anon, authenticated, service_role;
grant select, insert, update, delete on table public.customer_addresses to service_role;

create table if not exists public.otop_shipping_settings (
  id text primary key default 'default' check (id = 'default'),
  enabled boolean not null default true,
  domestic_base_fee numeric(12,2) not null default 60 check (domestic_base_fee >= 0),
  free_shipping_threshold numeric(12,2) null check (free_shipping_threshold is null or free_shipping_threshold >= 0),
  estimated_min_days integer not null default 2 check (estimated_min_days between 1 and 30),
  estimated_max_days integer not null default 5 check (estimated_max_days between estimated_min_days and 60),
  updated_at timestamptz not null default now()
);

insert into public.otop_shipping_settings (
  id, enabled, domestic_base_fee, free_shipping_threshold, estimated_min_days, estimated_max_days
) values ('default', true, 60, 1500, 2, 5)
on conflict (id) do nothing;

