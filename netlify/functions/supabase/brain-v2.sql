create table if not exists public.guest_semantic_memory (
  id bigint generated by default as identity primary key,
  guest_id uuid not null references public.guests(id) on delete cascade,
  memory_key text not null check (memory_key ~ '^[a-z0-9_]{1,48}$'),
  memory_value jsonb not null,
  confidence numeric(4,3) not null default 0.700 check (confidence >= 0 and confidence <= 1),
  source_channel text not null check (source_channel in ('web','line','facebook','messenger','backoffice')),
  evidence_count integer not null default 1 check (evidence_count >= 1),
  status text not null default 'active' check (status in ('active','superseded')),
  first_observed_at timestamptz not null default now(),
  last_observed_at timestamptz not null default now(),
  unique (guest_id, memory_key)
);

create index if not exists guest_semantic_memory_guest_idx on public.guest_semantic_memory(guest_id, status, last_observed_at desc);

create table if not exists public.world_facts (
  fact_key text primary key check (fact_key ~ '^[a-z0-9_\.]{1,80}$'),
  category text not null,
  fact_value jsonb not null,
  verified boolean not null default false,
  active boolean not null default true,
  source text null,
  updated_at timestamptz not null default now()
);

