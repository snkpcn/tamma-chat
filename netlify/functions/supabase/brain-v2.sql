  reason_code text not null check (reason_code in ('booking_help','accessibility_help','complaint','other')),
  source_channel text not null check (source_channel in ('web','line','facebook','messenger','backoffice')),
  status text not null default 'pending' check (status in ('pending','claimed','resolved','cancelled')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz null
